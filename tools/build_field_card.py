"""Build docs/resources/field-card.md: every lab's one thing, key takeaways and Monday moves.

The field card is a take-home summary of the course. It is generated from the labs so it can
never drift from them:

* ``one_thing`` from each lab's front matter,
* the bullets under ``## Key takeaways``,
* the numbered moves inside the ``!!! harbor "Back in your own harbor"`` admonition.

Usage: python tools/build_field_card.py [--check]   (--check exits 1 if the page is stale)
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = DOCS / "resources" / "field-card.md"


def front_matter(text: str) -> tuple[dict, str]:
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}, text
    return yaml.safe_load(m.group(1)) or {}, text[m.end():]


def section(body: str, heading: str) -> str:
    m = re.search(rf"^## {re.escape(heading)}\s*\n(.*?)(?=^## |\Z)", body, re.S | re.M)
    return m.group(1).strip() if m else ""


def harbor_moves(body: str) -> list[str]:
    m = re.search(r'^!!! harbor "[^"]*"\n((?:    .*\n|\s*\n)+)', body, re.M)
    if not m:
        return []
    block = "\n".join(line[4:] if line.startswith("    ") else line for line in m.group(1).splitlines())
    return [re.sub(r"\s+", " ", x).strip() for x in re.findall(r"^\d+\.\s+(.*(?:\n(?!\d+\.).+)*)", block, re.M)]


def bullets(md: str) -> list[str]:
    return [re.sub(r"\s+", " ", x).strip() for x in re.findall(r"^- (.*(?:\n(?!- ).+)*)", md, re.M)]


def build() -> str:
    class _Loose(yaml.SafeLoader):
        pass
    _Loose.add_multi_constructor("", lambda loader, suffix, node: None)  # ignore !!python/name: tags
    cfg = yaml.load((ROOT / "mkdocs.yml").read_text(), Loader=_Loose)
    days = {d["n"]: d for d in (cfg.get("extra") or {}).get("days", [])}
    labs = []
    for p in sorted(DOCS.glob("day-*/lab-*.md")):
        meta, body = front_matter(p.read_text())
        if meta.get("lab"):
            labs.append((meta, body, p))
    labs.sort(key=lambda x: int(x[0]["lab"]))

    out = [
        "---",
        "title: Your Field Card",
        "field_card: true",
        "---",
        "",
        "# Your Field Card",
        "",
        '<p class="hp-fc-lede">Twelve voyages on one page: the one thing to remember from each lab, its key takeaways, '
        "and the moves to make in your own Azure DevOps when you get back. Print it, or save it as a PDF "
        "(<kbd>Ctrl</kbd>/<kbd>Cmd</kbd> + <kbd>P</kbd>), and pin it next to your monitor.</p>",
        "",
        "<!-- Generated by tools/build_field_card.py from the labs. Edit the labs, not this page. -->",
        "",
    ]
    current_day = None
    for meta, body, path in labs:
        day = int(meta["day"])
        if day != current_day:
            current_day = day
            d = days.get(day, {})
            out += [f"## Day {day} · {d.get('name', '')}", ""]
            if d.get("theme"):
                out += [f'<p class="hp-fc-day">{d["theme"]}</p>', ""]
        rel = path.relative_to(DOCS).as_posix()
        out += [f'<div class="hp-fc" markdown>', "",
                f'<p class="hp-fc__num">Lab {meta["lab"]}</p>', "",
                f'### [{meta["title"]}](../{rel})', ""]
        if meta.get("one_thing"):
            out += [f'<p class="hp-fc__one">{meta["one_thing"]}</p>', ""]
        tk = bullets(section(body, "Key takeaways"))
        mv = harbor_moves(body)
        if tk:
            out += ['<p class="hp-fc__label">Key takeaways</p>', ""] + [f"- {t}" for t in tk] + [""]
        if mv:
            out += ['<p class="hp-fc__label hp-fc__label--harbor">Back in your own harbor</p>', ""]
            out += [f"{i}. {t}" for i, t in enumerate(mv, 1)] + [""]
        out += ["</div>", ""]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python tools/build_field_card.py")
            return 1
        print("field card is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
