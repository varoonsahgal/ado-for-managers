"""Build docs/slides/index.html from slides-src/*.html and the labs.

The slide sources are hand-written HTML partials, concatenated in file-name order. Two kinds of
placeholder are filled from the labs so the deck can never drift from them:

* ``<!--TK:N-->``      becomes Lab N's takeaways slide: its ``one_thing`` and its ``## Key takeaways``
* ``<!--ONE-THINGS-->`` becomes a grid of every lab's ``one_thing``

Usage: python tools/build_slides.py [--check]   (--check exits 1 if the deck is stale)
"""
from __future__ import annotations

import argparse
import hashlib
import html
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "slides-src"
OUT = ROOT / "docs" / "slides" / "index.html"
sys.path.insert(0, str(ROOT / "tools"))
from build_field_card import bullets, front_matter, section  # noqa: E402

DAY_PART = {1: "Day 1 · Charting the Waters", 2: "Day 2 · The Lighthouse", 3: "Day 3 · Setting the Course"}
SHORT = {
    1: "Explore the Program", 2: "Monday Morning Manager", 3: "Query Toolkit", 4: "Sprint Delivery Report",
    5: "Command Center", 6: "Which Team Needs Help?", 7: "Cross-Team Bottleneck", 8: "Executive Status Review",
    9: "Meet the Deadline?", 10: "Personas", 11: "Why Is the Dashboard Wrong?", 12: "Capstone",
}


def inline(md: str) -> str:
    """The small slice of Markdown the takeaways use: bold, italics, code, links."""
    s = html.escape(md, quote=False)
    s = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", s)
    s = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
    s = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<i>\1</i>", s)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    return s


def labs() -> dict[int, dict]:
    out = {}
    for p in sorted((ROOT / "docs").glob("day-*/lab-*.md")):
        meta, body = front_matter(p.read_text())
        if meta.get("lab"):
            out[int(meta["lab"])] = {"meta": meta, "keys": bullets(section(body, "Key takeaways"))}
    return out


def split_lead(bullet: str) -> tuple[str, str]:
    """'**The order is the decision.** When rank...' -> ('The order is the decision.', 'When rank...')."""
    m = re.match(r"\*\*(.+?)\*\*\s*(.*)", bullet)
    return (m.group(1), m.group(2)) if m else (bullet, "")


def takeaway_slide(n: int, lab: dict) -> str:
    m = lab["meta"]
    parts = [split_lead(k) for k in lab["keys"]]
    items = "\n".join(f"        <li><b>{inline(lead)}</b></li>" for lead, _ in parts)
    notes = "".join(f"<p><b>{inline(lead)}</b> {inline(rest)}</p>" for lead, rest in parts)
    return f"""<section class="slide sandy d{m['day']}" data-title="Lab {n} · Key takeaways" data-part="{DAY_PART[m['day']]}" data-section="Day {m['day']} · Lab {n} · {SHORT[n]}">
  <div class="tk content">
    <div class="onething rise">
      <div class="ey">If you remember one thing from Lab {n}</div>
      <p>{inline(str(m.get('one_thing', '')))}</p>
    </div>
    <div>
      <div class="eyebrow"><svg class="icon sm" style="--c:var(--brass)"><use href="#i-key"/></svg>Lab {n} · Key takeaways</div>
      <ol class="keys">
{items}
      </ol>
    </div>
  </div>
  <aside class="notes">{notes}<p>Generated from Lab {n}'s one thing and Key takeaways. Ask: which of these would have changed a decision you made last month?</p></aside>
</section>"""


def one_things(all_labs: dict[int, dict]) -> str:
    cells = "\n".join(
        f'      <div class="ot"><b>{n:02d}</b><span>{inline(str(lab["meta"].get("one_thing", "")))}</span></div>'
        for n, lab in sorted(all_labs.items())
    )
    return f'<div class="ots mt">\n{cells}\n    </div>'


def shot_bars(deck: str) -> str:
    """Give every screenshot window the validated location bar from tools/shots.yaml."""
    shots = yaml.safe_load((ROOT / "tools" / "shots.yaml").read_text()) or {}

    def bar(m: re.Match) -> str:
        text = (shots.get(m.group(4)) or {}).get("bar")
        return m.group(1) + (html.escape(text, quote=False) if text else m.group(2)) + m.group(3)

    pattern = r'(<div class="bar"><i></i><i></i><i></i><span>)([^<]*)(</span></div><img src="\.\./assets/shots/([\w-]+)\.png")'
    return re.sub(pattern, bar, deck)


def build() -> str:
    all_labs = labs()
    deck = "".join(p.read_text() for p in sorted(SRC.glob("*.html")))
    deck = re.sub(r"<!--TK:(\d+)-->", lambda m: takeaway_slide(int(m.group(1)), all_labs[int(m.group(1))]), deck)
    deck = deck.replace("<!--ONE-THINGS-->", one_things(all_labs))
    deck = shot_bars(deck)
    for asset in ("deck.css", "deck.js"):  # cache-bust: a new version gets a new URL
        digest = hashlib.sha1((OUT.parent / asset).read_bytes()).hexdigest()[:10]
        deck = deck.replace(f'"{asset}"', f'"{asset}?v={digest}"')
    banner = "<!-- Generated by tools/build_slides.py from slides-src/ and the labs. Edit those, not this file. -->\n"
    return deck.replace("<!doctype html>\n", "<!doctype html>\n" + banner, 1)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if docs/slides/index.html is stale")
    args = ap.parse_args()
    text = build()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python tools/build_slides.py", file=sys.stderr)
            return 1
        print("slides up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    count = text.count('<section class="slide')
    print(f"wrote {OUT.relative_to(ROOT)} ({count} slides)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
